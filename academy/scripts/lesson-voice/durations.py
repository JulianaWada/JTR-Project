"""
Writes components/animated-lesson/voice.ts: the length of every narration MP3 (needs ffprobe).
Run from the academy folder after make_voice.py:  python scripts/lesson-voice/durations.py
"""
import glob, json, os, subprocess

secs = {}
for d in sorted(glob.glob("private/lessons/*/*/")):
    course, lesson = d.rstrip("/").split("/")[-2:]
    files = sorted(glob.glob(d + "step-*.mp3"))
    probe = lambda f: float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f]).decode())
    secs[f"{course}/{lesson}"] = [round(probe(f), 2) for f in files]

body = "\n".join(f'  "{k}": {json.dumps(v)},' for k, v in secs.items())
with open(os.path.join("components", "animated-lesson", "voice.ts"), "w") as f:
    f.write(f"""/*
 * Recorded narration (Ezinne, Nigerian English) for the animated lessons: one MP3 per step in
 * private/lessons/<course>/<lesson>/step-NN.mp3, with its length in seconds.
 * Generated by scripts/lesson-voice/durations.py after make_voice.py. Do not edit by hand.
 */
export const VOICE_SECONDS: Record<string, number[]> = {{
{body}
}};
""")
